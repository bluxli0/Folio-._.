export const FolderSandboxPanel: React.FC<FolderSandboxPanelProps> = ({
  workspaceId,
  designSystem,
  onWorkspaceFilesSnapshot,
}) => {
  const [files, setFiles] = useState<WorkspaceFileEntry[]>([]);
  const [entryFolders, setEntryFolders] = useState<string[]>([]);
  const [selectedEntryFolder, setSelectedEntryFolder] = useState<string>('');
  const [activeFilePath, setActiveFilePath] = useState<string>('build_site.py');
  const [editorText, setEditorText] = useState<string>(STARTER_PYTHON_FOLDER_SCRIPT);
  const [isDirty, setIsDirty] = useState<boolean>(false);
  const [saveSuccess, setSaveSuccess] = useState<boolean>(false);

  const [newFilePathInput, setNewFilePathInput] = useState<string>('');
  const [showNewFileRow, setShowNewFileRow] = useState<boolean>(false);

  // Script execution state
  const [isRunningScript, setIsRunningScript] = useState<boolean>(false);
  const [execStdout, setExecStdout] = useState<string>('');
  const [execStderr, setExecStderr] = useState<string>('');
  const [execRuntime, setExecRuntime] = useState<string>('');
  const [execExitCode, setExecExitCode] = useState<number | null>(null);

  // Live Folder Render pane state
  const [subView, setSubView] = useState<'render' | 'editor' | 'github'>('render');
  const [renderNonce, setRenderNonce] = useState<number>(0);
  const [viewportWidth, setViewportWidth] = useState<'full' | 'mobile'>('full');

  // GitHub state
  const [ghStatus, setGhStatus] = useState<GitHubStatus>({ configured: false, connected: false });
  const [ghRepos, setGhRepos] = useState<GitHubRepoSummary[]>([]);
  const [ghRepoInput, setGhRepoInput] = useState<string>('');
  const [ghBranchInput, setGhBranchInput] = useState<string>('');
  const [ghSubpathInput, setGhSubpathInput] = useState<string>('');
  const [isImportingGh, setIsImportingGh] = useState<boolean>(false);
  const [ghMessage, setGhMessage] = useState<string | null>(null);
  const [ghFallbackAuthUrl, setGhFallbackAuthUrl] = useState<string | null>(null);

  const folderUploadRef = useRef<HTMLInputElement>(null);

  const syncDesignCssToWorkspace = useCallback(async () => {
    try {
      await fetch(`/api/workspace/${encodeURIComponent(workspaceId)}/files`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          designSystemCss: buildDesignSystemCss(designSystem),
        }),
      });
    } catch {
      // Non-fatal
    }
  }, [workspaceId, designSystem]);

  useEffect(() => {
    void syncDesignCssToWorkspace();
    setRenderNonce((n) => n + 1);
  }, [syncDesignCssToWorkspace]);

  const refreshFiles = useCallback(async () => {
    try {
      const res = await fetch(`/api/workspace/${encodeURIComponent(workspaceId)}/files`);
      if (!res.ok) return;
      const data = (await res.json()) as {
        files: WorkspaceFileEntry[];
        entryFolders: string[];
      };
      setFiles(data.files);
      setEntryFolders(data.entryFolders);
      if (data.entryFolders.length > 0 && !data.entryFolders.includes(selectedEntryFolder)) {
        setSelectedEntryFolder(data.entryFolders[0]);
      }
    } catch {
      // Ignore network hiccup
    }
  }, [workspaceId, selectedEntryFolder]);

  useEffect(() => {
    void refreshFiles();
  }, [refreshFiles]);

  // Snapshot text files for JSON bundle export when files change
  useEffect(() => {
    if (!onWorkspaceFilesSnapshot || files.length === 0) return;
    let cancelled = false;
    const textFiles = files.filter((f) => f.isText).slice(0, 20);
    Promise.all(
      textFiles.map(async (f) => {
        try {
          const r = await fetch(
            `/api/workspace/${encodeURIComponent(workspaceId)}/file?path=${encodeURIComponent(f.path)}`
          );
          if (!r.ok) return null;
          const d = (await r.json()) as { path: string; content: string };
          return { path: d.path, content: d.content };
        } catch {
          return null;
        }
      })
    ).then((loaded) => {
      if (cancelled) return;
      const valid = loaded.filter((x): x is { path: string; content: string } => Boolean(x));
      if (valid.length > 0) {
        onWorkspaceFilesSnapshot(valid);
      }
    });
    return () => {
      cancelled = true;
    };
  }, [files, workspaceId, onWorkspaceFilesSnapshot]);

  // Load GitHub status + listen for OAuth popup postMessage
  const loadGitHubStatus = useCallback(async () => {
    try {
      const res = await fetch('/api/github/status');
      if (!res.ok) return;
      const data = (await res.json()) as GitHubStatus;
      setGhStatus(data);
      if (data.connected) {
        const reposRes = await fetch('/api/github/repos');
        if (reposRes.ok) {
          const reposJson = (await reposRes.json()) as { repos?: GitHubRepoSummary[] };
          setGhRepos(reposJson.repos || []);
        }
      } else {
        setGhRepos([]);
      }
    } catch {
      // Ignore
    }
  }, []);

  useEffect(() => {
    void loadGitHubStatus();
    const handleMsg = (event: MessageEvent) => {
      const origin = event.origin;
      if (!origin.endsWith('.run.app') && !origin.includes('localhost')) return;
      if (event.data?.type === 'GITHUB_OAUTH_SUCCESS') {
        setGhFallbackAuthUrl(null);
        setGhMessage('Connected to GitHub account.');
        void loadGitHubStatus();
      }
    };
    window.addEventListener('message', handleMsg);
    return () => window.removeEventListener('message', handleMsg);
  }, [loadGitHubStatus]);

  const handleOpenFile = async (relPath: string) => {
    try {
      const res = await fetch(
        `/api/workspace/${encodeURIComponent(workspaceId)}/file?path=${encodeURIComponent(relPath)}`
      );
      const data = (await res.json()) as { content?: string; error?: string };
      if (!res.ok) throw new Error(data.error || 'Failed to read file.');
      setActiveFilePath(relPath);
      setEditorText(data.content || '');
      setIsDirty(false);
      setSubView('editor');
    } catch (err) {
      setExecStderr(err instanceof Error ? err.message : 'Unable to open file.');
    }
  };

  const handleSaveCurrentFile = async () => {
    if (!activeFilePath.trim()) return;
    try {
      const res = await fetch(`/api/workspace/${encodeURIComponent(workspaceId)}/files`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          designSystemCss: buildDesignSystemCss(designSystem),
          files: [{ path: activeFilePath.trim(), content: editorText }],
        }),
      });
      const data = (await res.json()) as {
        files?: WorkspaceFileEntry[];
        entryFolders?: string[];
        error?: string;
      };
      if (!res.ok) throw new Error(data.error || 'Save failed.');
      if (data.files) setFiles(data.files);
      if (data.entryFolders) setEntryFolders(data.entryFolders);
      setIsDirty(false);
      setSaveSuccess(true);
      setTimeout(() => setSaveSuccess(false), 1500);
      setRenderNonce((n) => n + 1);
    } catch (err) {
      setExecStderr(err instanceof Error ? err.message : 'Save failed.');
    }
  };

  const handleRunScript = async (overridePath?: string, overrideCode?: string) => {
    const targetPath = overridePath || activeFilePath || 'build_site.py';
    const targetCode = overrideCode !== undefined ? overrideCode : overridePath ? undefined : editorText;

    setIsRunningScript(true);
    setExecStdout('');
    setExecStderr('');
    setExecExitCode(null);

    try {
      await syncDesignCssToWorkspace();
      const res = await fetch(`/api/workspace/${encodeURIComponent(workspaceId)}/execute`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          filePath: targetPath,
          code: targetCode,
        }),
      });
      const data = (await res.json()) as {
        stdout?: string;
        stderr?: string;
        exitCode?: number;
        runtime?: string;
        files?: WorkspaceFileEntry[];
        entryFolders?: string[];
        error?: string;
      };
      if (!res.ok) {
        throw new Error(data.error || 'Execution failed.');
      }
      setExecStdout(data.stdout || '');
      setExecStderr(data.stderr || '');
      setExecExitCode(typeof data.exitCode === 'number' ? data.exitCode : 0);
      setExecRuntime(data.runtime || 'Workspace Runner');
      if (data.files) setFiles(data.files);
      if (data.entryFolders) {
        setEntryFolders(data.entryFolders);
        if (data.entryFolders.length > 0) {
          setSelectedEntryFolder(data.entryFolders[0]);
          setSubView('render');
        }
      }
      setIsDirty(false);
      setRenderNonce((n) => n + 1);
    } catch (err) {
      setExecStderr(err instanceof Error ? err.message : 'Script execution failed.');
    } finally {
      setIsRunningScript(false);
    }
  };

  const handleCreateNewFile = async (e: React.FormEvent) => {
    e.preventDefault();
    const cleaned = newFilePathInput.trim().replace(/^\/+/, '');
    if (!cleaned) return;
    setActiveFilePath(cleaned);
    const starter = cleaned.endsWith('.html')
      ? '<!doctype html>\n<html>\n<head>\n  <meta charset="utf-8" />\n  <link rel="stylesheet" href="style.css" />\n</head>\n<body>\n  <h1>Hello Folder</h1>\n  <script src="app.js"></script>\n</body>\n</html>'
      : cleaned.endsWith('.css')
      ? 'body { font-family: system-ui, sans-serif; background: var(--surface-color, #111827); color: var(--text-color, #fff); }'
      : cleaned.endsWith('.py')
      ? 'import os\nprint("Ready inside sandbox folder!")'
      : '// Script file\nconsole.log("Loaded");';
    setEditorText(starter);
    setShowNewFileRow(false);
    setNewFilePathInput('');
    setSubView('editor');

    await fetch(`/api/workspace/${encodeURIComponent(workspaceId)}/files`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        files: [{ path: cleaned, content: starter }],
      }),
    });
    void refreshFiles();
  };

  const handleDeleteFile = async (relPath: string) => {
    const res = await fetch(
      `/api/workspace/${encodeURIComponent(workspaceId)}/file?path=${encodeURIComponent(relPath)}`,
      { method: 'DELETE' }
    );
    if (res.ok) {
      const data = (await res.json()) as {
        files: WorkspaceFileEntry[];
        entryFolders: string[];
      };
      setFiles(data.files);
      setEntryFolders(data.entryFolders);
    }
  };

  const handleFolderUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const fileList = e.target.files;
    if (!fileList || fileList.length === 0) return;

    const payloadFiles: Array<{ path: string; content: string; encoding: 'utf8' | 'base64' }> = [];
    for (const file of Array.from(fileList).slice(0, 80)) {
      const rel = (file as File & { webkitRelativePath?: string }).webkitRelativePath || file.name;
      // Strip top-level chosen folder name if all files share it
      const parts = rel.split('/');
      const cleanRel = parts.length > 1 ? parts.slice(1).join('/') : rel;
      if (file.size > 512 * 1024) continue;
      const buf = await file.arrayBuffer();
      const bytes = new Uint8Array(buf);
      let binary = '';
      for (let i = 0; i < bytes.length; i += 1) {
        binary += String.fromCharCode(bytes[i]);
      }
      payloadFiles.push({
        path: cleanRel,
        content: btoa(binary),
        encoding: 'base64',
      });
    }

    const res = await fetch(`/api/workspace/${encodeURIComponent(workspaceId)}/files`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        clearBefore: true,
        designSystemCss: buildDesignSystemCss(designSystem),
        files: payloadFiles,
      }),
    });
    if (res.ok) {
      const data = (await res.json()) as {
        files: WorkspaceFileEntry[];
        entryFolders: string[];
      };
      setFiles(data.files);
      setEntryFolders(data.entryFolders);
      if (data.entryFolders.length > 0) {
        setSelectedEntryFolder(data.entryFolders[0]);
        setSubView('render');
      }
      setRenderNonce((n) => n + 1);
    }
    e.target.value = '';
  };

  const handleConnectGitHub = async () => {
    setGhMessage(null);
    setGhFallbackAuthUrl(null);
    try {
      const res = await fetch('/api/github/auth/url');
      const data = (await res.json()) as { url?: string; error?: string };
      if (!res.ok || !data.url) {
        setGhMessage(data.error || 'Unable to start GitHub OAuth.');
        return;
      }
      const popup = window.open(data.url, 'github_oauth_popup', 'width=620,height=720');
      if (!popup) {
        setGhFallbackAuthUrl(data.url);
        setGhMessage('Popup blocked — use the direct Authorize link below.');
      }
    } catch (err) {
      setGhMessage(err instanceof Error ? err.message : 'GitHub connection failed.');
    }
  };

  const handleDisconnectGitHub = async () => {
    await fetch('/api/github/logout', { method: 'POST' });
    setGhMessage('Disconnected GitHub account.');
    void loadGitHubStatus();
  };

  const handleImportGitHubRepo = async (repoOverride?: string) => {
    const repoTarget = (repoOverride || ghRepoInput).trim();
    if (!repoTarget) {
      setGhMessage('Enter a repository like "owner/repo" or full GitHub URL.');
      return;
    }
    setIsImportingGh(true);
    setGhMessage(null);
    try {
      const res = await fetch('/api/github/import', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          repo: repoTarget,
          branch: ghBranchInput.trim() || undefined,
          subpath: ghSubpathInput.trim() || undefined,
          workspaceId,
        }),
      });
      const data = (await res.json()) as {
        owner?: string;
        repo?: string;
        branch?: string;
        importedCount?: number;
        files?: WorkspaceFileEntry[];
        entryFolders?: string[];
        error?: string;
      };
      if (!res.ok) throw new Error(data.error || 'GitHub import failed.');
      if (data.files) setFiles(data.files);
      if (data.entryFolders) {
        setEntryFolders(data.entryFolders);
        if (data.entryFolders.length > 0) {
          setSelectedEntryFolder(data.entryFolders[0]);
        }
      }
      setGhMessage(
        `Imported ${data.importedCount ?? 0} files from ${data.owner}/${data.repo} (${data.branch}).`
      );
      setRenderNonce((n) => n + 1);
      if (data.entryFolders && data.entryFolders.length > 0) {
        setSubView('render');
      } else {
        setSubView('editor');
      }
    } catch (err) {
      setGhMessage(err instanceof Error ? err.message : 'Failed to import GitHub repo.');
    } finally {
      setIsImportingGh(false);
    }
  };

  const runnableScripts = useMemo(
    () =>
      files.filter((f) => /\.(py|js|ts|sh)$/i.test(f.path)),
    [files]
  );

  const folderRenderUrl = useMemo(() => {
    const folderClean = selectedEntryFolder.replace(/^\/+|\/+$/g, '');
    return folderClean
      ? `/workspace-site/${encodeURIComponent(workspaceId)}/${folderClean}/`
      : `/workspace-site/${encodeURIComponent(workspaceId)}/`;
  }, [workspaceId, selectedEntryFolder]);

  return (
    <div className="flex-1 min-h-0 flex flex-col overflow-hidden bg-white dark:bg-[#171717]">
      {/* Sub-navigation & Folder Actions */}
      <div className="px-3 sm:px-4 py-2 border-b border-neutral-200 dark:border-white/10 bg-[#fafafa] dark:bg-[#1c1d21] flex flex-wrap items-center justify-between gap-2 shrink-0">
        <div className="flex items-center gap-1 rounded-xl bg-neutral-200/70 dark:bg-[#2a2c32] p-0.5">
          <button
            type="button"
            onClick={() => setSubView('render')}
            className={`px-2.5 py-1 rounded-lg text-xs font-medium transition-colors whitespace-nowrap ${
              subView === 'render'
                ? 'bg-white dark:bg-[#3b3e46] text-[#0d0d0d] dark:text-white shadow-xs'
                : 'text-neutral-600 dark:text-neutral-300'
            }`}
          >
            Render Folder ({entryFolders.length})
          </button>
          <button
            type="button"
            onClick={() => setSubView('editor')}
            className={`px-2.5 py-1 rounded-lg text-xs font-medium transition-colors whitespace-nowrap ${
              subView === 'editor'
                ? 'bg-white dark:bg-[#3b3e46] text-[#0d0d0d] dark:text-white shadow-xs'
                : 'text-neutral-600 dark:text-neutral-300'
            }`}
          >
            Files &amp; Python ({files.length})
          </button>
          <button
            type="button"
            onClick={() => setSubView('github')}
            className={`inline-flex items-center gap-1 px-2.5 py-1 rounded-lg text-xs font-medium transition-colors whitespace-nowrap ${
              subView === 'github'
                ? 'bg-white dark:bg-[#3b3e46] text-[#0d0d0d] dark:text-white shadow-xs'
                : 'text-neutral-600 dark:text-neutral-300'
            }`}
          >
            <Github className="w-3.5 h-3.5" />
            <span>GitHub</span>
          </button>
        </div>

        <div className="flex items-center gap-1.5">
          <input
            ref={folderUploadRef}
            type="file"
            // @ts-expect-error webkitdirectory is standard in Chromium/WebKit for folder uploads
            webkitdirectory=""
            multiple
            className="hidden"
            onChange={handleFolderUpload}
          />
          <button
            type="button"
            onClick={() => folderUploadRef.current?.click()}
            className="inline-flex items-center gap-1 px-2.5 py-1 rounded-lg border border-neutral-200 dark:border-white/15 text-xs font-medium text-[#0d0d0d] dark:text-[#ececec] hover:bg-neutral-100 dark:hover:bg-white/10 whitespace-nowrap"
          >
            <Upload className="w-3.5 h-3.5" />
            <span>Upload Folder</span>
          </button>
          <button
            type="button"
            onClick={() => handleRunScript('build_site.py', STARTER_PYTHON_FOLDER_SCRIPT)}
            disabled={isRunningScript}
            title="Run sample Python script to generate site/index.html, style.css, and app.js"
            className="inline-flex items-center gap-1 px-2.5 py-1 rounded-lg bg-[#0d0d0d] dark:bg-white text-white dark:text-[#0d0d0d] text-xs font-medium hover:opacity-90 disabled:opacity-50 whitespace-nowrap"
          >
            {isRunningScript ? (
              <Loader2 className="w-3.5 h-3.5 animate-spin" />
            ) : (
              <Play className="w-3.5 h-3.5 fill-current" />
            )}
            <span>Build Sample Folder (Py)</span>
          </button>
        </div>
      </div>

      {/* Main SubView Area */}
      {subView === 'render' && (
        <div className="flex-1 min-h-0 flex flex-col">
          <div className="px-3 sm:px-4 py-2 border-b border-neutral-200 dark:border-white/10 bg-white dark:bg-[#1a1b1f] flex flex-wrap items-center justify-between gap-2 text-xs">
            <div className="flex items-center gap-2 min-w-0">
              <FolderOpen className="w-4 h-4 text-blue-500 shrink-0" />
              <select
                value={selectedEntryFolder}
                onChange={(e) => {
                  setSelectedEntryFolder(e.target.value);
                  setRenderNonce((n) => n + 1);
                }}
                aria-label="Select folder containing index.html"
                className="h-7 rounded-lg border border-neutral-200 dark:border-white/15 bg-[#f5f5f5] dark:bg-[#26282e] px-2 text-xs font-mono text-[#0d0d0d] dark:text-white"
              >
                {entryFolders.length === 0 ? (
                  <option value="">/ (no index.html yet)</option>
                ) : (
                  entryFolders.map((folder) => (
                    <option key={folder || 'root'} value={folder}>
                      /{folder ? `${folder}/index.html` : 'index.html'}
                    </option>
                  ))
                )}
              </select>
              <code className="hidden sm:inline text-[11px] font-mono text-neutral-500 dark:text-neutral-400 truncate max-w-[200px]">
                {folderRenderUrl}
              </code>
            </div>

            <div className="flex items-center gap-1 shrink-0">
              <button
                type="button"
                onClick={() => setViewportWidth((v) => (v === 'full' ? 'mobile' : 'full'))}
                title={viewportWidth === 'full' ? 'Mobile (375px)' : 'Full width'}
                className="inline-flex items-center justify-center w-7 h-7 rounded-lg text-neutral-600 dark:text-neutral-300 hover:bg-neutral-100 dark:hover:bg-white/10"
              >
                {viewportWidth === 'full' ? (
                  <Smartphone className="w-3.5 h-3.5" />
                ) : (
                  <Monitor className="w-3.5 h-3.5" />
                )}
              </button>
              <button
                type="button"
                onClick={() => setRenderNonce((n) => n + 1)}
                title="Reload folder render"
                className="inline-flex items-center justify-center w-7 h-7 rounded-lg text-neutral-600 dark:text-neutral-300 hover:bg-neutral-100 dark:hover:bg-white/10"
              >
                <RotateCw className="w-3.5 h-3.5" />
              </button>
              <a
                href={folderRenderUrl}
                target="_blank"
                rel="noopener noreferrer"
                className="inline-flex items-center gap-1 px-2.5 py-1 rounded-lg bg-blue-600 text-white text-[11px] font-medium hover:bg-blue-500 whitespace-nowrap"
              >
                <span>Open Folder Live</span>
                <ExternalLink className="w-3 h-3" />
              </a>
            </div>
          </div>

          <div className="flex-1 min-h-0 flex justify-center bg-neutral-100 dark:bg-[#101216] overflow-auto">
            {entryFolders.length === 0 ? (
              <div className="self-center max-w-md p-6 text-center space-y-3">
                <FolderPlus className="w-8 h-8 mx-auto text-neutral-400" />
                <h4 className="text-sm font-semibold text-[#0d0d0d] dark:text-white">
                  No renderable folder yet
                </h4>
                <p className="text-xs text-neutral-500 dark:text-neutral-400 leading-relaxed">
                  Click <strong>Build Sample Folder (Py)</strong> above to generate{' '}
                  <code>site/index.html</code>, <code>site/style.css</code>, and{' '}
                  <code>site/app.js</code> using Python, upload a local folder, or import a repository from <strong>GitHub</strong>.
                </p>
              </div>
            ) : (
              <iframe
                key={`${folderRenderUrl}-${renderNonce}`}
                src={folderRenderUrl}
                title="Sandbox multi-file folder renderer"
                sandbox="allow-scripts allow-same-origin allow-forms allow-popups"
                className={`h-full border-0 bg-white transition-all duration-150 ${
                  viewportWidth === 'mobile'
                    ? 'w-[375px] max-w-full my-3 rounded-2xl shadow-lg border border-neutral-300 dark:border-white/15'
                    : 'w-full'
                }`}
              />
            )}
          </div>
        </div>
      )}

      {subView === 'editor' && (
        <div className="flex-1 min-h-0 flex flex-col sm:flex-row overflow-hidden">
          {/* File Explorer Sidebar */}
          <div className="sm:w-56 shrink-0 border-b sm:border-b-0 sm:border-r border-neutral-200 dark:border-white/10 bg-[#fafafa] dark:bg-[#1c1d21] flex flex-col max-h-48 sm:max-h-none">
            <div className="px-3 py-2 border-b border-neutral-200 dark:border-white/10 flex items-center justify-between text-xs">
              <span className="font-semibold text-[#0d0d0d] dark:text-white">Workspace</span>
              <button
                type="button"
                onClick={() => setShowNewFileRow((v) => !v)}
                className="inline-flex items-center gap-1 px-2 py-0.5 rounded-md bg-neutral-200/80 dark:bg-white/10 text-[11px] font-medium text-[#0d0d0d] dark:text-white"
              >
                <Plus className="w-3 h-3" />
                <span>File</span>
              </button>
            </div>

            {showNewFileRow && (
              <form onSubmit={handleCreateNewFile} className="p-2 border-b border-neutral-200 dark:border-white/10 flex gap-1">
                <input
                  type="text"
                  value={newFilePathInput}
                  onChange={(e) => setNewFilePathInput(e.target.value)}
                  placeholder="site/index.html"
                  className="flex-1 min-w-0 h-7 rounded border border-neutral-300 dark:border-white/15 bg-white dark:bg-[#14161a] px-2 text-[11px] font-mono text-[#0d0d0d] dark:text-white"
                />
                <button
                  type="submit"
                  className="h-7 px-2 rounded bg-[#0d0d0d] dark:bg-white text-white dark:text-[#0d0d0d] text-[11px] font-medium"
                >
                  Add
                </button>
              </form>
            )}

            <div className="flex-1 overflow-y-auto p-1.5 space-y-0.5 chat-scroll">
              {files.map((f) => {
                const selected = f.path === activeFilePath;
                return (
                  <div
                    key={f.path}
                    className={`group flex items-center justify-between gap-1 px-2 py-1.5 rounded-lg text-xs cursor-pointer ${
                      selected
                        ? 'bg-blue-600/15 text-blue-700 dark:text-blue-300 font-medium'
                        : 'text-neutral-700 dark:text-neutral-300 hover:bg-neutral-200/60 dark:hover:bg-white/5'
                    }`}
                    onClick={() => f.isText && void handleOpenFile(f.path)}
                  >
                    <span className="inline-flex items-center gap-1.5 min-w-0 truncate font-mono text-[11px]">
                      <FileCode2 className="w-3.5 h-3.5 shrink-0 opacity-70" />
                      <span className="truncate">{f.path}</span>
                    </span>
                    <button
                      type="button"
                      onClick={(e) => {
                        e.stopPropagation();
                        void handleDeleteFile(f.path);
                      }}
                      aria-label={`Delete ${f.path}`}
                      className="opacity-0 group-hover:opacity-100 text-neutral-400 hover:text-red-500 p-0.5"
                    >
                      <Trash2 className="w-3 h-3" />
                    </button>
                  </div>
                );
              })}
              {files.length === 0 && (
                <p className="p-2 text-[11px] text-neutral-500">
                  Run a Python script or add files to populate this sandbox folder.
                </p>
              )}
            </div>
          </div>

          {/* Code Editor + Script Output */}
          <div className="flex-1 min-h-0 flex flex-col bg-[#0d0d0d] text-[#ececec]">
            <div className="px-3 py-2 border-b border-white/10 flex flex-wrap items-center justify-between gap-2 text-xs">
              <div className="flex items-center gap-2 min-w-0">
                <input
                  type="text"
                  value={activeFilePath}
                  onChange={(e) => {
                    setActiveFilePath(e.target.value);
                    setIsDirty(true);
                  }}
                  aria-label="Active workspace file path"
                  className="h-7 rounded-md border border-white/15 bg-[#1b1c20] px-2 font-mono text-xs text-white w-48 max-w-full"
                />
                {isDirty && <span className="text-[11px] text-amber-400">unsaved</span>}
              </div>

              <div className="flex items-center gap-1.5">
                <button
                  type="button"
                  onClick={handleSaveCurrentFile}
                  className="inline-flex items-center gap-1 px-2.5 py-1 rounded-md border border-white/15 text-xs font-medium text-neutral-200 hover:bg-white/10"
                >
                  {saveSuccess ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Save className="w-3.5 h-3.5" />}
                  <span>{saveSuccess ? 'Saved' : 'Save'}</span>
                </button>
                {/\.(py|js|ts|sh)$/i.test(activeFilePath) && (
                  <button
                    type="button"
                    onClick={() => handleRunScript()}
                    disabled={isRunningScript}
                    className="inline-flex items-center gap-1 px-2.5 py-1 rounded-md bg-emerald-600 text-white text-xs font-medium hover:bg-emerald-500 disabled:opacity-50"
                  >
                    {isRunningScript ? (
                      <Loader2 className="w-3.5 h-3.5 animate-spin" />
                    ) : (
                      <Play className="w-3.5 h-3.5 fill-current" />
                    )}
                    <span>Run Script in Folder</span>
                  </button>
                )}
              </div>
            </div>

            <textarea
              value={editorText}
              onChange={(e) => {
                setEditorText(e.target.value);
                setIsDirty(true);
              }}
              spellCheck={false}
              className="flex-1 w-full resize-none bg-transparent p-3 font-mono text-xs leading-relaxed text-[#ececec] focus:outline-none chat-scroll"
            />

            {(execStdout || execStderr || execExitCode !== null) && (
              <div className="max-h-40 border-t border-white/10 bg-[#121316] p-2.5 font-mono text-xs overflow-y-auto chat-scroll space-y-1">
                <div className="flex items-center justify-between text-[11px] text-neutral-400">
                  <span className="inline-flex items-center gap-1.5">
                    <Terminal className="w-3.5 h-3.5" />
                    {execRuntime} {execExitCode !== null ? `· Exit ${execExitCode}` : ''}
                  </span>
                </div>
                {execStdout && (
                  <pre className="whitespace-pre-wrap text-emerald-300 m-0">{execStdout}</pre>
                )}
                {execStderr && (
                  <pre className="whitespace-pre-wrap text-red-400 m-0">{execStderr}</pre>
                )}
              </div>
            )}
          </div>
        </div>
      )}

      {subView === 'github' && (
        <div className="flex-1 min-h-0 overflow-y-auto p-3 sm:p-4 space-y-4 chat-scroll">
          {/* GitHub Account OAuth Connection */}
          <section className="rounded-xl border border-neutral-200 dark:border-white/10 bg-[#fafafa] dark:bg-[#202227] p-3.5 space-y-3">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div className="flex items-center gap-2">
                <Github className="w-4 h-4 text-[#0d0d0d] dark:text-white" />
                <div>
                  <h4 className="text-xs font-semibold text-[#0d0d0d] dark:text-white">
                    GitHub Account &amp; Repo Script Runner
                  </h4>
                  <p className="text-[11px] text-neutral-500 dark:text-neutral-400">
                    Connect via OAuth for private repos or import any public GitHub repository URL directly.
                  </p>
                </div>
              </div>

              {ghStatus.connected && ghStatus.user ? (
                <div className="flex items-center gap-2">
                  {ghStatus.user.avatar_url && (
                    <img
                      src={ghStatus.user.avatar_url}
                      alt={ghStatus.user.login}
                      referrerPolicy="no-referrer"
                      className="w-6 h-6 rounded-full"
                    />
                  )}
                  <span className="text-xs font-medium text-[#0d0d0d] dark:text-white">
                    @{ghStatus.user.login}
                  </span>
                  <button
                    type="button"
                    onClick={handleDisconnectGitHub}
                    className="px-2.5 py-1 rounded-lg border border-neutral-200 dark:border-white/15 text-xs text-neutral-600 dark:text-neutral-300 hover:bg-neutral-100 dark:hover:bg-white/10"
                  >
                    Disconnect
                  </button>
                </div>
              ) : (
                <button
                  type="button"
                  onClick={handleConnectGitHub}
                  className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-[#0d0d0d] dark:bg-white text-white dark:text-[#0d0d0d] text-xs font-medium hover:opacity-90"
                >
                  <Github className="w-3.5 h-3.5" />
                  <span>Connect GitHub</span>
                </button>
              )}
            </div>

            {ghFallbackAuthUrl && (
              <a
                href={ghFallbackAuthUrl}
                target="_blank"
                rel="noopener noreferrer"
                className="inline-flex items-center gap-1 text-xs text-blue-600 dark:text-blue-400 underline"
              >
                <span>Open GitHub OAuth Authorization</span>
                <ExternalLink className="w-3 h-3" />
              </a>
            )}

            {ghRepos.length > 0 && (
              <div className="space-y-1.5">
                <label className="block text-[11px] font-medium text-neutral-600 dark:text-neutral-400">
                  Your Connected Repositories
                </label>
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-1.5 max-h-40 overflow-y-auto chat-scroll">
                  {ghRepos.map((repo) => (
                    <button
                      key={repo.id}
                      type="button"
                      onClick={() => {
                        setGhRepoInput(repo.full_name);
                        setGhBranchInput(repo.default_branch);
                        void handleImportGitHubRepo(repo.full_name);
                      }}
                      className="flex items-center justify-between gap-2 px-2.5 py-2 rounded-lg border border-neutral-200 dark:border-white/10 bg-white dark:bg-[#15171b] text-left hover:border-blue-500/50 transition-colors"
                    >
                      <span className="truncate text-xs font-mono text-[#0d0d0d] dark:text-white">
                        {repo.full_name}
                      </span>
                      <span className="text-[10px] text-neutral-500 shrink-0">
                        {repo.private ? 'Private' : 'Public'}
                      </span>
                    </button>
                  ))}
                </div>
              </div>
            )}
          </section>

          {/* Direct Repo Importer */}
          <section className="rounded-xl border border-neutral-200 dark:border-white/10 bg-[#fafafa] dark:bg-[#202227] p-3.5 space-y-2.5">
            <h4 className="text-xs font-semibold text-[#0d0d0d] dark:text-white flex items-center gap-1.5">
              <FolderGit2 className="w-4 h-4 text-blue-500" />
              <span>Clone / Import GitHub Folder into Sandbox</span>
            </h4>

            <div className="grid grid-cols-1 sm:grid-cols-4 gap-2">
              <input
                type="text"
                value={ghRepoInput}
                onChange={(e) => setGhRepoInput(e.target.value)}
                placeholder="owner/repo or https://github.com/..."
                className="sm:col-span-2 h-8 rounded-lg border border-neutral-200 dark:border-white/15 bg-white dark:bg-[#14161a] px-2.5 text-xs font-mono text-[#0d0d0d] dark:text-white"
              />
              <input
                type="text"
                value={ghBranchInput}
                onChange={(e) => setGhBranchInput(e.target.value)}
                placeholder="branch (auto)"
                className="h-8 rounded-lg border border-neutral-200 dark:border-white/15 bg-white dark:bg-[#14161a] px-2.5 text-xs font-mono text-[#0d0d0d] dark:text-white"
              />
              <input
                type="text"
                value={ghSubpathInput}
                onChange={(e) => setGhSubpathInput(e.target.value)}
                placeholder="subfolder (optional)"
                className="h-8 rounded-lg border border-neutral-200 dark:border-white/15 bg-white dark:bg-[#14161a] px-2.5 text-xs font-mono text-[#0d0d0d] dark:text-white"
              />
            </div>

            <div className="flex flex-wrap items-center justify-between gap-2">
              <button
                type="button"
                onClick={() => handleImportGitHubRepo()}
                disabled={isImportingGh}
                className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-blue-600 text-white text-xs font-medium hover:bg-blue-500 disabled:opacity-50"
              >
                {isImportingGh ? (
                  <Loader2 className="w-3.5 h-3.5 animate-spin" />
                ) : (
                  <FolderGit2 className="w-3.5 h-3.5" />
                )}
                <span>Import Repo Folder</span>
              </button>

              {ghMessage && (
                <span className="text-xs text-neutral-600 dark:text-neutral-300">{ghMessage}</span>
              )}
            </div>
          </section>

          {/* Runnable Scripts Found in Imported Folder */}
          <section className="rounded-xl border border-neutral-200 dark:border-white/10 bg-[#fafafa] dark:bg-[#202227] p-3.5 space-y-2.5">
            <h4 className="text-xs font-semibold text-[#0d0d0d] dark:text-white">
              Runnable Scripts in Sandbox Folder ({runnableScripts.length})
            </h4>

            {runnableScripts.length === 0 ? (
              <p className="text-xs text-neutral-500 dark:text-neutral-400">
                No <code>.py</code>, <code>.js</code>, <code>.ts</code>, or <code>.sh</code> scripts in the workspace yet. Import a GitHub repo or create a script on the Files tab.
              </p>
            ) : (
              <div className="space-y-1.5">
                {runnableScripts.map((script) => (
                  <div
                    key={script.path}
                    className="flex items-center justify-between gap-2 px-3 py-2 rounded-lg border border-neutral-200 dark:border-white/10 bg-white dark:bg-[#15171b]"
                  >
                    <button
                      type="button"
                      onClick={() => void handleOpenFile(script.path)}
                      className="text-xs font-mono text-[#0d0d0d] dark:text-white hover:underline truncate text-left"
                    >
                      {script.path}
                    </button>
                    <button
                      type="button"
                      onClick={() => void handleRunScript(script.path)}
                      disabled={isRunningScript}
                      className="inline-flex items-center gap-1 px-2.5 py-1 rounded-md bg-emerald-600 text-white text-[11px] font-medium hover:bg-emerald-500 shrink-0"
                    >
                      <Play className="w-3 h-3 fill-current" />
                      <span>Run</span>
                    </button>
                  </div>
                ))}
              </div>
            )}
          </section>
        </div>
      )}
    </div>
  );
};
