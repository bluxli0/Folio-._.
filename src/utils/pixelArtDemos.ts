function makeFrameFromRows(
  rows: string[],
  palette: Record<string, string>,
  width = 32,
  height = 32,
  hold = 1
): PixelArtFrame {
  const pixels: string[] = [];
  for (let y = 0; y < height; y += 1) {
    const row = rows[y] || '';
    for (let x = 0; x < width; x += 1) {
      const char = row[x] || '.';
      pixels.push(palette[char] || '');
    }
  }
  return {
    id: crypto.randomUUID(),
    pixels,
    hold,
  };
}

